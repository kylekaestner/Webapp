#!/usr/bin/env node
// Builds public/app.html from frontend/: the page template plus the app's script, split by feature
// into frontend/src/**.js and joined back together in the order listed in frontend/files.json.
//
// The files are joined as-is, in order, into the one <script> they came from, so they share one
// global scope exactly as before: every onclick="fn()" and every shared variable keeps working.
// Order matters for top-level `let`/`const` and code that runs at load; function declarations can
// live in any file.
//
//   node scripts/build-frontend.js           build once
//   node scripts/build-frontend.js --watch   rebuild on every save under frontend/ (local dev)
//
// public/app.html is generated and committed (so deploys need no build). Don't edit it by hand: its
// first line carries a hash of the rest, and the build refuses to overwrite a file that no longer
// matches it, so a hand edit is never silently lost.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const FRONTEND = path.join(ROOT, 'frontend');
const TEMPLATE = path.join(FRONTEND, 'app.template.html');
const FILES = path.join(FRONTEND, 'files.json');
const OUT = path.join(ROOT, 'public', 'app.html');
const PLACEHOLDER = '@@APP_SCRIPT@@';
// The note goes on the line after <!DOCTYPE html>: anything before the doctype risks old-style rendering.
const HEADER_RE = /\n<!-- GENERATED by scripts\/build-frontend\.js from frontend\/ \(edit those, not this file\)\. build:([0-9a-f]{12}) -->(?=\n)/;

const hash = s => crypto.createHash('sha256').update(s).digest('hex').slice(0, 12);
// Always LF: git on Windows may check files out with CRLF, which must not look like a hand edit.
const lf = s => s.replace(/\r\n/g, '\n');

function build() {
    const template = lf(fs.readFileSync(TEMPLATE, 'utf8'));
    const files = JSON.parse(fs.readFileSync(FILES, 'utf8'));
    const lines = template.split('\n');
    const at = lines.findIndex(l => l.trim() === PLACEHOLDER);
    if (at < 0 || lines.filter(l => l.trim() === PLACEHOLDER).length !== 1) throw new Error(`${PLACEHOLDER} must appear exactly once in app.template.html`);
    const seen = new Set();
    let script = '';
    for (const rel of files) {
        if (seen.has(rel)) throw new Error(`${rel} is listed twice in files.json`);
        seen.add(rel);
        const text = lf(fs.readFileSync(path.join(FRONTEND, 'src', rel), 'utf8'));
        script += text.endsWith('\n') ? text : text + '\n';
    }
    // A file in src/ that files.json doesn't list would silently never load.
    const onDisk = [];
    (function walk(dir, pre) {
        for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
            if (e.isDirectory()) walk(path.join(dir, e.name), pre + e.name + '/');
            else if (e.name.endsWith('.js')) onDisk.push(pre + e.name);
        }
    })(path.join(FRONTEND, 'src'), '');
    const unlisted = onDisk.filter(f => !seen.has(f));
    if (unlisted.length) throw new Error(`not in files.json (add them in load order): ${unlisted.join(', ')}`);

    const body = lines.slice(0, at).join('\n') + '\n' + script + lines.slice(at + 1).join('\n');
    const nl = body.indexOf('\n');
    const out = body.slice(0, nl) + `\n<!-- GENERATED by scripts/build-frontend.js from frontend/ (edit those, not this file). build:${hash(body)} -->` + body.slice(nl);

    if (fs.existsSync(OUT)) {
        const cur = lf(fs.readFileSync(OUT, 'utf8'));
        const m = cur.match(HEADER_RE);
        if (m && hash(cur.replace(m[0], '')) !== m[1] && !process.argv.includes('--force')) {
            throw new Error('public/app.html was edited by hand since the last build. Move those edits into frontend/ '
                + '(compare with `git diff public/app.html`), or rerun with --force to discard them.');
        }
        if (cur === out) return false;
    }
    fs.writeFileSync(OUT, out);
    return true;
}

function run() {
    try {
        const changed = build();
        console.log(`[build-frontend] ${changed ? 'wrote' : 'unchanged'} public/app.html  ${new Date().toLocaleTimeString()}`);
        return true;
    } catch (e) { console.error('[build-frontend] ' + e.message); return false; }
}

if (process.argv.includes('--watch')) {
    run();
    let t = null;
    fs.watch(FRONTEND, { recursive: true }, () => { clearTimeout(t); t = setTimeout(run, 100); });
    console.log('[build-frontend] watching frontend/ ...');
} else if (!run()) process.exit(1);
